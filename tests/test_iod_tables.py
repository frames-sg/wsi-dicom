import importlib.util
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATOR = REPO_ROOT / "scripts" / "generate-iod-tables.py"
OUTPUT_DIR = REPO_ROOT / "src" / "validation" / "iod"
# Directory holding the pinned DocBook part03.xml, part06.xml and part10.xml.
SOURCE_DIR_VARIABLE = "WSI_DICOM_DOCBOOK_DIR"


def load_generator():
    spec = importlib.util.spec_from_file_location("generate_iod_tables", GENERATOR)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {GENERATOR}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_generator(*arguments):
    return subprocess.run(
        [sys.executable, str(GENERATOR), *arguments],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def source_dir():
    value = os.environ.get(SOURCE_DIR_VARIABLE)
    return Path(value) if value else None


class IodTableTests(unittest.TestCase):
    def test_generated_files_record_the_pinned_edition_and_sources(self):
        generator = load_generator()
        for name in generator.OUTPUT_FILES:
            text = (OUTPUT_DIR / name).read_text(encoding="utf-8")
            self.assertTrue(text.startswith("// @generated by scripts/generate-iod-tables.py"))
            self.assertIn(f"from DICOM {generator.EDITION}.", text.splitlines()[0])
            recorded = dict(re.findall(r"^// Source (\S+) SHA-256 ([0-9a-f]{64})$", text, re.M))
            self.assertEqual(recorded, generator.SOURCES, name)

    def test_check_mode_accepts_the_checked_in_tables(self):
        sources = source_dir()
        if sources is None:
            self.skipTest(f"set {SOURCE_DIR_VARIABLE} to the pinned DocBook sources")
        result = run_generator("--source-dir", str(sources), "--check")
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_check_mode_rejects_stale_tables(self):
        sources = source_dir()
        if sources is None:
            self.skipTest(f"set {SOURCE_DIR_VARIABLE} to the pinned DocBook sources")
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary)
            for name in load_generator().OUTPUT_FILES:
                shutil.copy(OUTPUT_DIR / name, output / name)
            tables = output / "tables.rs"
            tables.write_text(tables.read_text(encoding="utf-8") + "// edited\n", encoding="utf-8")
            result = run_generator("--source-dir", str(sources), "--output-dir", str(output), "--check")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("stale generated tables", result.stderr)

    def test_unpinned_sources_are_rejected(self):
        with tempfile.TemporaryDirectory() as temporary:
            sources = Path(temporary)
            for name in load_generator().SOURCES:
                (sources / name).write_text("<book/>", encoding="utf-8")
            result = run_generator("--source-dir", str(sources), "--check")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("expected pinned 2026d digest", result.stderr)


if __name__ == "__main__":
    unittest.main()
